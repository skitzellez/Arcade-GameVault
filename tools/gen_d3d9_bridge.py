# gen_d3d9_bridge.py: writes src/d3d9_sig32.inc from the Windows SDK's d3d9.h - every method of the D3D9 interfaces a
# 32-bit game uses, in vtable order, with a code per argument for the 32-bit -> 64-bit bridge (d3d9_bridge32.cpp):
#   u  32-bit number (UINT, DWORD, BOOL, INT, enums)      f  float
#   p  pointer to data with the same layout in 32 and 64 bit   h  handle (HWND, HMONITOR, HDC: sign-extended)
#   I  interface in (the stand-in is swapped for the real object)    O<n>  interface out (wrapped as interface n)
#   P  D3DPRESENT_PARAMETERS*   C  D3DDEVICE_CREATION_PARAMETERS*   R  D3DLOCKED_RECT*   B  D3DLOCKED_BOX*
#   D  HDC* (a handle out: 4 bytes for the game)   V  void** of a buffer Lock     Q  void** of QueryInterface / GetContainer (with the IID before it)   n  HANDLE*
# and a return code: h HRESULT/number, f float, v void.
import re, sys
from pathlib import Path

H = Path(r"C:/Program Files (x86)/Windows Kits/10/Include/10.0.26100.0/shared/d3d9.h").read_text(encoding="latin-1")
IFACES = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DStateBlock9", "IDirect3DSwapChain9", "IDirect3DResource9",
          "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DBaseTexture9",
          "IDirect3DTexture9", "IDirect3DVolumeTexture9", "IDirect3DCubeTexture9", "IDirect3DVertexBuffer9",
          "IDirect3DIndexBuffer9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DQuery9"]
index = {n: i for i, n in enumerate(IFACES)}


def code(ptype, iface, method):
    t = re.sub(r"\bCONST\b|\bconst\b", "", ptype).strip()
    m0 = re.match(r"^(.*?[\s*])(\w+)$", t)   # drop the parameter name (after a space or a *)
    if m0 and m0.group(1).strip():
        t = m0.group(1)
    t = t.replace(" ", "")
    if t in ("REFIID", "REFGUID"):
        return "p"
    m = re.match(r"(IDirect3D\w*9)\*\*$", t)
    if m:
        target = m.group(1)
        if target not in index:
            sys.exit("unknown interface " + target)
        return "O%d" % index[target]
    if re.match(r"IDirect3D\w*9\*$", t):
        return "I"
    if t == "void**":
        return "Q" if method in ("QueryInterface", "GetContainer") else "V"
    if t == "HANDLE*":
        return "n"
    if t == "HDC*":
        return "D"
    if t == "D3DPRESENT_PARAMETERS*":
        return "P"
    if t == "D3DDEVICE_CREATION_PARAMETERS*":
        return "C"
    if t == "D3DLOCKED_RECT*":
        return "R"
    if t == "D3DLOCKED_BOX*":
        return "B"
    if t in ("HWND", "HMONITOR", "HDC"):
        return "h"
    if t == "float":
        return "f"
    if t.endswith("*") or t.startswith("LP"):
        return "p"
    return "u"


out = ["// generated by tools/gen_d3d9_bridge.py from the Windows SDK d3d9.h - do not edit",
       "static const MethodSig32 kSig32[][128] = {"]
counts = []
for name in IFACES:
    m = re.search(r"DECLARE_INTERFACE_\(%s,\s*\w+\)\s*\{(.*?)\n\};" % name, H, re.S)
    body = m.group(1)
    methods = re.findall(r"STDMETHOD(?:_\(\s*([\w ]+?)\s*,\s*(\w+)\)|\((\w+)\))\(THIS_?\s*(.*?)\)\s*PURE;", body, re.S)
    rows = []
    for ret, mname1, mname2, params in methods:
        mname = mname1 or mname2
        ret = ret.strip() if ret else "HRESULT"
        rcode = "f" if ret == "float" else "v" if ret == "void" else "h"
        params = params.strip()
        codes = []
        if params:
            for p in params.split(","):
                codes.append(code(p.strip(), name, mname))
        rows.append('{"%s", \'%s\', "%s"}' % (mname, rcode, " ".join(codes)))
    counts.append(len(rows))
    out.append("    { // %d %s: %d methods" % (index[name], name, len(rows)))
    for r in rows:
        out.append("        " + r + ",")
    out.append("    },")
out.append("};")
iids = []
for name in IFACES:
    m = re.search(r"DEFINE_GUID\(IID_%s,\s*(.*?)\);" % name, H)
    v = [x.strip() for x in m.group(1).split(",")]
    iids.append("{%s, %s, %s, {%s}}" % (v[0], v[1], v[2], ", ".join(v[3:])))
out.append("static const GUID kIid32[] = {%s};" % ", ".join(iids))
out.append("static const int kMethods32[] = {%s};" % ", ".join(map(str, counts)))
out.append("enum Iface32 { %s };" % ", ".join("k%s = %d" % (n[1:], i) for i, n in enumerate(IFACES)))
Path(__file__).resolve().parent.parent.joinpath("src", "d3d9_sig32.inc").write_text("\n".join(out) + "\n",
                                                                                       encoding="utf-8")
print(dict(zip(IFACES, counts)))
